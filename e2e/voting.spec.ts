import { test, expect, type Page } from '@playwright/test'

async function openAdmin(page: Page) {
  await page.goto('/#hasil')
  await page.locator('.protected-page').getByRole('button', { name: 'Masuk dashboard', exact: true }).click()
}

test('galeri, pencarian, voting sekali, dan pilihan bertahan setelah reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.demo-banner')).toBeVisible()
  await expect(page.getByRole('heading', { name: '56 tahun cerita.' , exact: false })).toBeVisible()
  await expect(page.locator('header').getByText('Hasil Voting', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Masuk admin', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Buka dashboard hasil', exact: true })).toHaveCount(0)
  await expect(page.locator('.logo-card')).toHaveCount(14)
  await page.getByRole('textbox', { name: 'Cari nomor logo' }).fill('logo 14')
  await expect(page.locator('.logo-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Lihat detail Logo 14', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Pilih logo ini', exact: true }).click()
  await expect(page.getByText('Sudah yakin memilih?')).toBeVisible()
  await page.getByRole('button', { name: 'Ya, pilih Logo 14', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Suaramu berarti.' })).toBeVisible()
  await page.getByRole('button', { name: 'Kembali ke galeri', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pilihan kamu', exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.getByText('Terima kasih, suaramu sudah tercatat!')).toBeVisible()
  await expect(page.locator('.logo-card-chosen')).toHaveCount(1)
  await expect(page.locator('.vote-button:enabled')).toHaveCount(0)
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('hasil diproteksi, login ditolak jika salah, ekspor CSV dan logout berjalan', async ({ page }) => {
  await page.goto('/#hasil')
  await expect(page.getByRole('heading', { name: 'Ruang suara almamater.' })).toBeVisible()
  await expect(page.locator('.ranking-table')).toHaveCount(0)
  await page.getByRole('button', { name: 'Masuk dashboard', exact: true }).click()
  await page.getByRole('textbox', { name: 'Username', exact: true }).fill('admin123')
  await page.getByLabel('Kata sandi', { exact: true }).fill('salah')
  await page.getByRole('dialog').getByRole('button', { name: 'Masuk dashboard', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Username atau kata sandi salah')
  await page.getByLabel('Kata sandi', { exact: true }).fill('admin123')
  await page.getByRole('dialog').getByRole('button', { name: 'Masuk dashboard', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Suara almamater.' })).toBeVisible()
  await expect(page.locator('.ranking-table tbody tr')).toHaveCount(14)
  await expect(page.getByText('Menunggu suara pertama')).toBeVisible()
  await page.locator('.skip-link').focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#hasil$/)
  await expect(page.locator('#main-content')).toBeFocused()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Ekspor CSV', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^hasil-voting-stm56-.*\.csv$/)
  await page.getByRole('button', { name: 'Keluar dashboard', exact: true }).click()
  await expect(page.getByRole('heading', { name: '56 tahun cerita.', exact: false })).toBeVisible()
  await page.goto('/#hasil')
  await expect(page.locator('.ranking-table')).toHaveCount(0)
})

test('suara yang dikirim tampil di dashboard dengan peringkat dan persentase benar', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.locator('.logo-card').nth(3).getByRole('button', { name: 'Vote logo ini', exact: true }).click()
  await page.getByRole('button', { name: 'Ya, pilih Logo 04', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Suaramu berarti.' })).toBeVisible()
  await page.getByRole('button', { name: 'Kembali ke galeri', exact: true }).click()
  await openAdmin(page)
  await page.getByRole('textbox', { name: 'Username', exact: true }).fill('admin123')
  await page.getByLabel('Kata sandi', { exact: true }).fill('admin123')
  await page.getByRole('dialog').getByRole('button', { name: 'Masuk dashboard', exact: true }).click()
  const row = page.locator('.ranking-table tbody tr').first()
  await expect(row).toContainText('Logo 04')
  await expect(row).toContainText('100.0%')
  await expect(page.locator('.highlight-stat')).toContainText('Logo 04')
  await page.reload()
  await expect(page.locator('.ranking-table tbody tr')).toHaveCount(14)
  await page.locator('img').evaluateAll((images) => images.forEach((img) => { img.loading = 'eager' }))
  await page.evaluate(async () => {
    await document.fonts.ready
    await Promise.all(Array.from(document.images).map((image) => image.decode().catch(() => {})))
    if (document.activeElement instanceof HTMLElement) document.activeElement.blur()
    window.scrollTo({ top: 0, behavior: 'instant' })
  })
  await page.screenshot({ path: `test-results/dashboard-${testInfo.project.name}.png`, fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('gambar WebP tersedia, galeri dan dashboard tampil tanpa overflow', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.locator('.artboard-preview img').evaluateAll((images) => images.forEach((img) => { (img as HTMLImageElement).loading = 'eager' }))
  await page.locator('.logo-card').last().scrollIntoViewIfNeeded()
  await expect(async () => {
    const images = await page.locator('.artboard-preview img').evaluateAll((images) => images.every((img) => (img as HTMLImageElement).complete && (img as HTMLImageElement).naturalWidth >= 1000))
    expect(images).toBe(true)
  }).toPass()
  await page.evaluate(async () => {
    await document.fonts.ready
    await Promise.all(Array.from(document.images).map((image) => image.decode()))
  })
  for (const image of await page.locator('.artboard-preview img').all()) await image.scrollIntoViewIfNeeded()
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: `test-results/voting-${testInfo.project.name}.png`, fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
